/** カテゴリIDから商品を引く。 */
export function byCategory(cat) {
  return PRODUCTS.filter((p) => p.cat === cat);
}

/** マニアック度で絞る（0=王道 / 1=知る人ぞ知る / 2=マニアック）。 */
export function byManiac(level) {
  return PRODUCTS.filter((p) => p.maniac === level);
}

/** 季節で絞る。'all' の商品は常に含める。 */
export function bySeason(season) {
  return PRODUCTS.filter((p) => p.season === season || p.season === 'all');
}
